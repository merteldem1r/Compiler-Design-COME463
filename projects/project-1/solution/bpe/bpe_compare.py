"""bpe_compare.py: compare our Flex lexer (build/ankac) with GPT-4's BPE tokenizer.

Project 1, Part B, Step 5. Run it from the folder that contains the Makefile:

    make bpe

which runs  .venv/bin/python <this file> <test folder> > results.md
The output is Markdown; the report quotes its numbers.
"""
import subprocess
import sys
from pathlib import Path

import tiktoken

# Paths are relative to where we are run (the Makefile's folder), so the same script
# works in the repository (tests/lexer) and in the submission zip (tests).
ANKAC = Path("build") / "ankac"
TEST_DIR = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("tests") / "lexer"
TESTS = sorted(TEST_DIR.glob("*.anka"))

enc = tiktoken.encoding_for_model("gpt-4")           # = cl100k_base


# ---------------------------------------------------------------- our lexer
def lex(text):
    """Run ankac on `text`. Return the output in order, as (name, text) pairs:
    a token is ("IDENT", "x"); an error is ("ERROR", "unexpected character '@'")."""
    out = subprocess.run([str(ANKAC), "--tokens"], input=text.encode(),
                         capture_output=True).stdout.decode("utf-8", "replace")
    items = []
    for line in out.splitlines():
        # "LINE 3: IDENT        'x'"  ->  name = IDENT, lexeme = x
        name = line.split(":", 1)[1].split()[0]
        if name == "END":
            continue
        if name == "ERROR":
            items.append(("ERROR", line.split("ERROR", 1)[1].strip()))
        else:
            items.append((name, line[line.index("'") + 1:line.rindex("'")]))
    return items


def tokens_of(items):
    return [(n, t) for n, t in items if n != "ERROR"]


def show_lex(text):
    items = lex(text)
    parts = []
    for name, t in items:
        if name == "ERROR":
            parts.append(f"**ERROR** {t}")
        elif name in ("IDENT", "INT_LIT", "FLOAT_LIT", "STRING_LIT"):
            parts.append(f"{name}({t})")
        else:
            parts.append(name)
    return len(tokens_of(items)), " ".join(parts)


# ---------------------------------------------------------------- BPE
def bpe(text):
    """Return the BPE tokens as readable strings (a space is shown as ␣)."""
    pieces = []
    for t in enc.encode(text):
        raw = enc.decode_single_token_bytes(t)
        try:
            s = raw.decode("utf-8")
        except UnicodeDecodeError:                   # half of a multi-byte character
            s = "".join(f"\\x{b:02X}" for b in raw)
        pieces.append(s.replace(" ", "␣").replace("\n", "\\n"))
    return pieces


def show_bpe(text):
    pieces = bpe(text)
    return len(pieces), " · ".join(f"`{p}`" for p in pieces)


# ---------------------------------------------------------------- report
print("# BPE vs our lexer: results\n")
print(f"Tokenizer: `tiktoken.encoding_for_model(\"gpt-4\")` = `{enc.name}` (tiktoken {tiktoken.__version__}). "
      "Lexer: `build/ankac --tokens`. Generated by `bpe_compare.py`; do not edit by hand.\n")

print("## 1. Whole test files\n")
print("*Lexer tokens* excludes `END` and errors. *BPE, lexemes only* runs BPE on the lexer's lexemes "
      "joined by single spaces, i.e. the same content without comments and extra whitespace.\n")
print("| File | Characters | Lexer tokens | Lexer errors | BPE tokens (whole file) | BPE, lexemes only |")
print("|---|---:|---:|---:|---:|---:|")
total = [0, 0, 0, 0, 0]
for path in TESTS:
    text = path.read_text(encoding="utf-8")
    items = lex(text)
    tokens = tokens_of(items)
    joined = " ".join(lexeme for _, lexeme in tokens)
    row = [len(text), len(tokens), len(items) - len(tokens), len(enc.encode(text)), len(enc.encode(joined))]
    total = [a + b for a, b in zip(total, row)]
    print(f"| `{path.name}` | " + " | ".join(str(x) for x in row) + " |")
print("| **Total** | " + " | ".join(f"**{x}**" for x in total) + " |\n")

print("## 2. Small inputs side by side\n")
PROBES = [
    "let x = 42;",            # the lecture example; Q2
    "42", "1000", "12345",    # how BPE cuts numbers
    "3.14159", "2.5e-3",
    "ifx", "if x",            # maximal munch vs BPE
    "==", "a-->b", "x**=2",
    "007",
    "x@y",                    # Q3: an error character
    "let ğ = 2;",             # non-ASCII outside a string
]
print("| Input | Lexer (#) | Lexer tokens | BPE (#) | BPE tokens |")
print("|---|---:|---|---:|---|")
for p in PROBES:
    ln, lt = show_lex(p)
    bn, bt = show_bpe(p)
    print(f"| `{p}` | {ln} | {lt} | {bn} | {bt} |")
print()

print("## 3. Byte-level fallback (why BPE never reports an error)\n")
for p in ["@", "ğ", "𓂀"]:
    bn, bt = show_bpe(p)
    print(f"- `{p}` ({len(p.encode())} UTF-8 byte{'s' if len(p.encode()) > 1 else ''}) → {bn} BPE token{'s' if bn > 1 else ''}: {bt}")
print()

print("## 4. Turkish vs English (Q5)\n")
print("| Sentence | Words | Characters | UTF-8 bytes | BPE tokens | Tokens per word | BPE tokens |")
print("|---|---:|---:|---:|---:|---:|---|")
for s in ["The compiler parses tokens", "Derleyici belirteçleri ayrıştırır"]:
    bn, bt = show_bpe(s)
    words = len(s.split())
    print(f"| {s} | {words} | {len(s)} | {len(s.encode())} | {bn} | {bn / words:.1f} | {bt} |")
print()

print("## 5. Same input, different tokenizer generations\n")
print("| Encoding | Used by | `let x = 42;` |")
print("|---|---|---|")
for name, used_by in [("gpt2", "GPT-2"), ("cl100k_base", "GPT-4, GPT-3.5"), ("o200k_base", "GPT-4o")]:
    e = tiktoken.get_encoding(name)
    pieces = [e.decode([t]).replace(" ", "␣") for t in e.encode("let x = 42;")]
    print(f"| `{name}` | {used_by} | {len(pieces)}: " + " · ".join(f"`{p}`" for p in pieces) + " |")
